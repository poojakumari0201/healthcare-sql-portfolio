-- STEP 1: DATABASE SELECTION & INITIAL VIEW
-- Description: Selecting the database, viewing table records, and checking table structure[cite: 9]
USE healthcare_db;
SELECT * FROM healthcare;
DESCRIBE healthcare;

-- STEP 2: DATA CLEANING & TYPE CONVERSION
-- Description: Converting date columns to standard MySQL date format and permanently altering columns to DATE data type[cite: 10]
SET sql_mode = '';
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET `Date of Admission` = STR_TO_DATE(`Date of Admission`, '%Y-%m-%d'),
    `Discharge Date` = STR_TO_DATE(`Discharge Date`, '%Y-%m-%d');
ALTER TABLE healthcare
MODIFY COLUMN `Date of Admission` DATE,
MODIFY COLUMN `Discharge Date` DATE;
SET SQL_SAFE_UPDATES = 1;
DESCRIBE healthcare;

-- STEP 3: DATA INTEGRITY & QUALITY CHECKS (PATIENT COUNT)
-- Description: Comparing total patient count against unique patient count to verify data accuracy[cite: 11]
SELECT 
    COUNT(Patient_ID) AS Total_Patient,
    COUNT(DISTINCT Patient_ID) AS Total_Unique_Patient
FROM healthcare;

-- STEP 4: NULL VALUE AUDIT ACROSS COLUMNS
-- Description: Finding missing or NULL value counts across all columns in the dataset[cite: 12]
SELECT 
    SUM(CASE WHEN Patient_ID IS NULL THEN 1 ELSE 0 END) AS Null_Patient_ID,
    SUM(CASE WHEN Name IS NULL THEN 1 ELSE 0 END) AS Null_Name,
    SUM(CASE WHEN Age IS NULL THEN 1 ELSE 0 END) AS Null_Age,
    SUM(CASE WHEN Gender IS NULL THEN 1 ELSE 0 END) AS Null_Gender,
    SUM(CASE WHEN `Blood Type` IS NULL THEN 1 ELSE 0 END) AS Null_Blood_Type,
    SUM(CASE WHEN `Medical Condition` IS NULL THEN 1 ELSE 0 END) AS Null_Medical_Condition,
    SUM(CASE WHEN `Date of Admission` IS NULL THEN 1 ELSE 0 END) AS Null_Date_of_Admission,
    SUM(CASE WHEN Doctor IS NULL THEN 1 ELSE 0 END) AS Null_Doctor,
    SUM(CASE WHEN Hospital IS NULL THEN 1 ELSE 0 END) AS Null_Hospital,
    SUM(CASE WHEN `Insurance Provider` IS NULL THEN 1 ELSE 0 END) AS Null_Insurance_Provider,
    SUM(CASE WHEN `Billing Amount` IS NULL THEN 1 ELSE 0 END) AS Null_Billing_Amount,
    SUM(CASE WHEN `Room Number` IS NULL THEN 1 ELSE 0 END) AS Null_Room_Number,
    SUM(CASE WHEN `Admission Type` IS NULL THEN 1 ELSE 0 END) AS Null_Admission_Type,
    SUM(CASE WHEN `Discharge Date` IS NULL THEN 1 ELSE 0 END) AS Null_Discharge_Date,
    SUM(CASE WHEN Medication IS NULL THEN 1 ELSE 0 END) AS Null_Medication,
    SUM(CASE WHEN `Test Results` IS NULL THEN 1 ELSE 0 END) AS Null_Test_Results
FROM healthcare;

-- STEP 5: TEXT STANDARDIZATION & NAME FORMATTING
-- Description: Formatting patient names into Proper Case using string manipulation functions[cite: 13]
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET Name = CONCAT(
    UPPER(SUBSTRING(SUBSTRING_INDEX(TRIM(Name), ' ', 1), 1, 1)),
    LOWER(SUBSTRING(SUBSTRING_INDEX(TRIM(Name), ' ', 1), 2)),
    ' ',
    UPPER(SUBSTRING(SUBSTRING_INDEX(TRIM(Name), ' ', -1), 1, 1)),
    LOWER(SUBSTRING(SUBSTRING_INDEX(TRIM(Name), ' ', -1), 2))
)
WHERE Name IS NOT NULL AND Name LIKE '% %';
SET SQL_SAFE_UPDATES = 1;

-- STEP 6: PATIENT DEMOGRAPHICS & AGE ANALYSIS
-- Description: Categorizing patients into age brackets and calculating average age grouped by gender[cite: 14]
SELECT 
    CASE 
        WHEN Age BETWEEN 18 AND 35 THEN 'Young (18-35)'
        WHEN Age BETWEEN 36 AND 60 THEN 'Adult (36-60)'
        WHEN Age > 60 THEN 'Senior Citizen (60+)'
        ELSE 'Under 18'
    END AS Age_Group,
    COUNT(*) AS Total_Patients
FROM healthcare
GROUP BY Age_Group
ORDER BY Total_Patients DESC;

SELECT 
    Gender,
    ROUND(AVG(Age), 2) AS Avg_Age
FROM healthcare
GROUP BY Gender;

-- STEP 7: BILLING & FINANCIAL ANALYSIS (PART 1)
-- Description: Filtering out negative billing anomalies to get overall billing statistics and medical condition breakdowns
SELECT 
    ROUND(AVG(`Billing Amount`), 2) AS Avg_Billing_Amount,
    ROUND(MIN(`Billing Amount`), 2) AS Min_Billing_Amount,
    ROUND(MAX(`Billing Amount`), 2) AS Max_Billing_Amount
FROM healthcare
WHERE `Billing Amount` >= 0;

SELECT 
    `Medical Condition`,
    ROUND(SUM(`Billing Amount`), 2) AS Total_Billing_Amount,
    ROUND(AVG(`Billing Amount`), 2) AS Avg_Billing_Amount
FROM healthcare
WHERE `Billing Amount` >= 0
GROUP BY `Medical Condition`
ORDER BY Total_Billing_Amount DESC;

-- STEP 8: REVENUE BY INSURANCE PROVIDER
-- Description: Calculating total revenue generated by each insurance provider
SELECT 
    `Insurance Provider`,
    ROUND(SUM(`Billing Amount`), 2) AS Total_Revenue
FROM healthcare
WHERE `Billing Amount` >= 0
GROUP BY `Insurance Provider`
ORDER BY Total_Revenue DESC;

-- STEP 9: HOSPITAL & DOCTOR PERFORMANCE
-- Description: Finding top 5 hospitals by patient admissions and counting patient workload per doctor
SELECT 
    Hospital,
    COUNT(Patient_ID) AS Total_Patients
FROM healthcare
GROUP BY Hospital
ORDER BY Total_Patients DESC
LIMIT 5;

SELECT 
    Doctor,
    COUNT(Patient_ID) AS Total_Patients
FROM healthcare
GROUP BY Doctor
ORDER BY Total_Patients DESC;

-- STEP 10: LENGTH OF STAY (LoS) & ADMISSION INSIGHTS
-- Description: Analyzing average billing by admission type, average length of stay by medical condition, and identifying top 10 longest stay patients
SELECT 
    `Admission Type`,
    ROUND(AVG(`Billing Amount`), 2) AS Avg_Billing_Amount
FROM healthcare
WHERE `Billing Amount` >= 0
GROUP BY `Admission Type`
ORDER BY Avg_Billing_Amount DESC;

SELECT 
    `Medical Condition`,
    ROUND(AVG(DATEDIFF(`Discharge Date`, `Date of Admission`)), 2) AS Avg_Length_of_Stay
FROM healthcare
GROUP BY `Medical Condition`
ORDER BY Avg_Length_of_Stay DESC;

SELECT 
    Patient_ID,
    Name,
    DATEDIFF(`Discharge Date`, `Date of Admission`) AS Length_of_Stay
FROM healthcare
ORDER BY Length_of_Stay DESC
LIMIT 10;

-- STEP 11: ROOM NUMBER & MEDICAL PATTERNS
-- Description: Analyzing room number admission frequency and discovering medical condition and blood type patterns
SELECT 
    `Room Number`,
    COUNT(Patient_ID) AS Total_Patient_Admitted
FROM healthcare
GROUP BY `Room Number`
ORDER BY Total_Patient_Admitted DESC;

SELECT 
    `Medical Condition`,
    `Blood Type`,
    COUNT(Patient_ID) AS Total_Patients
FROM healthcare
GROUP BY `Medical Condition`, `Blood Type`
ORDER BY Total_Patients DESC;

-- STEP 12: TEST RESULTS DISTRIBUTION & RISK TIER FEATURE ENGINEERING
-- Description: Calculating test results percentage distribution and creating a Risk Tier column based on age and medical condition
SELECT 
    `Test Results`,
    COUNT(Patient_ID) AS Total_Count,
    ROUND((COUNT(*) * 100.0 / (SELECT COUNT(*) FROM healthcare)), 2) AS Percentage
FROM healthcare
GROUP BY `Test Results`
ORDER BY Total_Count DESC;

SELECT DISTINCT(`Medical Condition`) FROM healthcare;

SET SQL_SAFE_UPDATES = 0;
ALTER TABLE healthcare ADD COLUMN Risk_Tier VARCHAR(20);
UPDATE healthcare
SET Risk_Tier = CASE 
    WHEN Age > 60 AND `Medical Condition` IN ('Cancer', 'Obesity', 'Diabetes', 'Asthma', 'Hypertension', 'Arthritis')
    THEN 'High Risk'
    WHEN Age > 40 THEN 'Moderate Risk'
    ELSE 'Low Risk'
END;
SET SQL_SAFE_UPDATES = 1;

-- STEP 13: FEATURE ENGINEERING & COST ANALYSIS
-- Description: Engineering new columns for cost per day, stay category duration brackets, and days difference calculation
SET SQL_SAFE_UPDATES = 1;
ALTER TABLE healthcare ADD COLUMN Cost_Per_Day Decimal(10,2);
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET Cost_Per_Day = ROUND(`Billing Amount` / NULLIF(DATEDIFF(`Discharge Date`, `Date of Admission`), 0), 2);

SET SQL_SAFE_UPDATES = 1;
UPDATE healthcare
SET `Cost_Per_Day` = 0
WHERE `Cost_Per_Day` < 0 OR `Cost_Per_Day` IS NULL;

ALTER TABLE healthcare ADD COLUMN Stay_Category VARCHAR(50);
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET Stay_Category = CASE 
    WHEN DATEDIFF(`Discharge Date`, `Date of Admission`) <= 5 THEN 'Short Stay (1-5 Days)'
    WHEN DATEDIFF(`Discharge Date`, `Date of Admission`) BETWEEN 6 AND 15 THEN 'Medium Stay (6-15 Days)'
    ELSE 'Long Stay (15+ Days)'
END;

SET SQL_SAFE_UPDATES = 1;
ALTER TABLE healthcare ADD COLUMN Days_Since_Last_Discharge INT;
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET Days_Since_Last_Discharge = DATEDIFF(`Discharge Date`, `Date of Admission`);

-- STEP 14: READMISSION FLAG & FINAL DATA CLEANING
-- Description: Creating readmission flag, cleaning negative billing amounts with absolute values, and permanently populating age groups
SET SQL_SAFE_UPDATES = 1;
ALTER TABLE healthcare ADD COLUMN Is_Readmitted_30days INT DEFAULT 0;
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET Is_Readmitted_30days = CASE 
    WHEN Days_Since_Last_Discharge > 0 AND Days_Since_Last_Discharge <= 10 THEN 1
    ELSE 0
END;

SET SQL_SAFE_UPDATES = 1;
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET `Billing Amount` = ROUND(ABS(`Billing Amount`), 2)
WHERE `Billing Amount` < 0;

SET SQL_SAFE_UPDATES = 1;
ALTER TABLE healthcare ADD COLUMN Age_Group VARCHAR(20);
SET SQL_SAFE_UPDATES = 0;
UPDATE healthcare
SET Age_Group = CASE 
    WHEN Age <= 20 THEN '0-20'
    WHEN Age <= 40 THEN '21-40'
    WHEN Age <= 60 THEN '41-60'
    ELSE '60+'
END;
SET SQL_SAFE_UPDATES = 1;